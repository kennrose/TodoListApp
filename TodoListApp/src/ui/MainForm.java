    public MainForm(TaskController controller) {
        this.controller = controller;
        initComponents();
        jTableListofTask.setModel(tableModel);
        jTableListofTask.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);

        jButtonSave.addActionListener(evt -> saveTask());
        jButtonDelete.addActionListener(evt -> deleteTask());
        jTableListofTask.getSelectionModel().addListSelectionListener(evt -> {
            if (!evt.getValueIsAdjusting()) loadSelectedTask();
        });
        refreshTaskList();
    }

    public void refreshTaskList() {
        if (controller == null) return;
        List<Task> tasks = controller.getAllTask();
        tasks.sort((a, b) -> String.valueOf(a.getPnum()).compareTo(String.valueOf(b.getPnum())));
        tableModel.setTasks(tasks);
    }

    private void saveTask() {
        if (controller == null) {
            JOptionPane.showMessageDialog(this, "Application controller is not initialized.");
            return;
        }
        String name = jTextFieldName.getText();
        String price = jTextFieldPrice.getText();
        String brand = jTextFieldBrand.getText();
        String model = jTextFieldModel.getText();
        String specs = jTextAreaSpecs.getText();

        boolean saved = selectedPnum == null
                ? controller.handleAddTask(name, price, brand, model, specs)
                : controller.handleUpdateTask(selectedPnum, name, price, brand, model, specs);

        if (!saved) {
            JOptionPane.showMessageDialog(this,
                    "Please complete all fields before saving.",
                    "Missing information", JOptionPane.WARNING_MESSAGE);
            return;
        }
        clearFields();
        JOptionPane.showMessageDialog(this, "Record saved successfully.");
    }

    private void deleteTask() {
        if (controller == null || selectedPnum == null) {
            JOptionPane.showMessageDialog(this, "Please select a record to delete.");
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete the selected record?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (choice == JOptionPane.YES_OPTION && controller.handleDeleteTask(selectedPnum)) {
            clearFields();
            JOptionPane.showMessageDialog(this, "Record deleted successfully.");
        }
    }

    private void loadSelectedTask() {
        int row = jTableListofTask.getSelectedRow();
        if (row < 0) return;
        int modelRow = jTableListofTask.convertRowIndexToModel(row);
        Task task = tableModel.getTask(modelRow);
        selectedPnum = task.getPnum();
        jTextFieldName.setText(task.getName());
        jTextFieldPrice.setText(task.getPrice());
        jTextFieldBrand.setText(task.getBrand());
        jTextFieldModel.setText(task.getModel());
        jTextAreaSpecs.setText(task.getSpecs());
    }

    private void clearFields() {
        selectedPnum = null;
        jTableListofTask.clearSelection();
        jTextFieldName.setText("");
        jTextFieldPrice.setText("");
        jTextFieldBrand.setText("");
        jTextFieldModel.setText("");
        jTextAreaSpecs.setText("");
    }

